#!/usr/bin/env bash
# SproutRoute - one-shot setup for Ubuntu Server 22.04 / 24.04.
# Installs Apache + PHP + MySQL, copies the app to /var/www/sproutroute,
# creates the database and a dedicated DB user, and enables the site.
#
# Usage (from the repository folder):
#   sudo bash deploy/setup.sh                      # serve on the server's IP
#   sudo DOMAIN=example.com bash deploy/setup.sh   # serve on a domain
#   sudo DOMAIN=example.com EMAIL=you@x.com HTTPS=1 bash deploy/setup.sh
#
# Safe to re-run: it updates the code and keeps the existing database,
# DB password and uploaded photos.
set -euo pipefail

APP_DIR="${APP_DIR:-/var/www/sproutroute}"
DOMAIN="${DOMAIN:-}"
HTTPS="${HTTPS:-0}"
EMAIL="${EMAIL:-}"
DB_NAME="sproutroute"
DB_USER="sproutroute"
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

if [[ $EUID -ne 0 ]]; then
    echo "Run this with sudo: sudo bash deploy/setup.sh" >&2
    exit 1
fi

echo "==> Installing Apache, PHP and MySQL"
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y apache2 mysql-server php libapache2-mod-php php-mysql php-mbstring rsync openssl

systemctl enable --now mysql apache2

echo "==> Copying the app to $APP_DIR"
mkdir -p "$APP_DIR"
rsync -a --delete \
    --exclude '.git' --exclude '.idea' \
    --exclude 'api/config.local.php' --exclude 'api/uploads/products/*' \
    "$REPO_DIR"/ "$APP_DIR"/
mkdir -p "$APP_DIR/api/uploads/products"

echo "==> Setting up the database"
CONFIG="$APP_DIR/api/config.local.php"
if [[ -f "$CONFIG" ]]; then
    DB_PASS="$(php -r '$c = require $argv[1]; echo $c["password"];' "$CONFIG")"
else
    DB_PASS="$(openssl rand -hex 16)"
fi

mysql <<SQL
CREATE DATABASE IF NOT EXISTS \`$DB_NAME\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '$DB_USER'@'localhost' IDENTIFIED BY '$DB_PASS';
ALTER USER '$DB_USER'@'localhost' IDENTIFIED BY '$DB_PASS';
GRANT ALL PRIVILEGES ON \`$DB_NAME\`.* TO '$DB_USER'@'localhost';
FLUSH PRIVILEGES;
SQL

TABLES="$(mysql -N -e "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='$DB_NAME'")"
if [[ "$TABLES" == "0" ]]; then
    echo "    Importing database/sproutroute.sql"
    mysql < "$REPO_DIR/database/sproutroute.sql"
else
    echo "    Database already has $TABLES tables - not re-importing"
fi

cat > "$CONFIG" <<PHP
<?php
// Generated by deploy/setup.sh - do not commit.
return [
    "host" => "127.0.0.1",
    "port" => 3306,
    "database" => "$DB_NAME",
    "username" => "$DB_USER",
    "password" => "$DB_PASS",
];
PHP

echo "==> Setting file permissions"
chown -R root:www-data "$APP_DIR"
find "$APP_DIR" -type d -exec chmod 755 {} +
find "$APP_DIR" -type f -exec chmod 644 {} +
chmod 640 "$CONFIG"
chown -R www-data:www-data "$APP_DIR/api/uploads"

echo "==> Configuring PHP upload limits"
PHP_VER="$(php -r 'echo PHP_MAJOR_VERSION.".".PHP_MINOR_VERSION;')"
cat > "/etc/php/$PHP_VER/apache2/conf.d/99-sproutroute.ini" <<INI
upload_max_filesize = 4M
post_max_size = 8M
expose_php = Off
display_errors = Off
log_errors = On
session.cookie_httponly = 1
INI

echo "==> Enabling the Apache site"
SERVER_NAME="${DOMAIN:-$(hostname -I | awk '{print $1}')}"
sed -e "s#__APP_DIR__#$APP_DIR#g" -e "s#__SERVER_NAME__#$SERVER_NAME#g" \
    "$REPO_DIR/deploy/sproutroute.conf" > /etc/apache2/sites-available/sproutroute.conf
a2enmod headers alias >/dev/null
a2ensite sproutroute >/dev/null
a2dissite 000-default >/dev/null 2>&1 || true
apache2ctl configtest
systemctl reload apache2

if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
    echo "==> Opening the firewall for Apache"
    ufw allow 'Apache Full'
fi

if [[ "$HTTPS" == "1" ]]; then
    if [[ -z "$DOMAIN" || -z "$EMAIL" ]]; then
        echo "HTTPS=1 needs DOMAIN and EMAIL set - skipping certificate." >&2
    else
        echo "==> Getting a free HTTPS certificate from Let's Encrypt"
        apt-get install -y certbot python3-certbot-apache
        certbot --apache -d "$DOMAIN" -m "$EMAIL" --agree-tos --redirect -n
    fi
fi

SCHEME="http"; [[ "$HTTPS" == "1" && -n "$DOMAIN" ]] && SCHEME="https"
echo
echo "Done. Open: $SCHEME://$SERVER_NAME/"
echo "Demo logins are listed in README.md / database/sproutroute.sql."
